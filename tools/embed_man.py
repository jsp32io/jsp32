#!/usr/bin/env python3
"""Embed man/**/*.md as an exact-byte, read-only firmware topic table."""
import argparse
from pathlib import Path
import re


def generate(root: Path) -> str:
    entries = []
    output = ['/* Generated by tools/embed_man.py. Do not edit. */',
              '#pragma once', '#include <stddef.h>',
              'typedef struct { const char *topic; const unsigned char *body; size_t size; } man_page_t;']
    for path in sorted(root.rglob('*.md')):
        parts = path.relative_to(root).with_suffix('').parts
        if any(not re.fullmatch(r'[a-z0-9][a-z0-9_-]*', part) for part in parts):
            raise ValueError(f'Invalid manual path: {path}')
        topic = '.'.join(parts)
        data = path.read_bytes()
        symbol = f'man_body_{len(entries)}'
        output.append(f'static const unsigned char {symbol}[] = {{')
        for offset in range(0, len(data), 20):
            output.append('    ' + ','.join(str(b) for b in data[offset:offset+20]) + ',')
        output.append('    0\n};')
        entries.append(f'    {{"{topic}", {symbol}, sizeof({symbol}) - 1}},')
    if not entries:
        raise ValueError('No manual pages found')
    output.append('static const man_page_t man_pages[] = {')
    output.extend(entries)
    output.append('};\n')
    return '\n'.join(output)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('root', type=Path)
    parser.add_argument('output', type=Path)
    args = parser.parse_args()
    args.output.write_text(generate(args.root), encoding='utf-8')
